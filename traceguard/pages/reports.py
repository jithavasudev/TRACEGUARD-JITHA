import streamlit as st
import db
from auth import require_login

user = require_login(["Admin"])
st.title("📑 Admin Reports")

batches = db.query("SELECT id, filename, uploaded_by, uploaded_at, row_count FROM upload_batch ORDER BY id DESC")
if batches.empty:
    st.info("No batches uploaded yet.")
    st.stop()
st.dataframe(batches, hide_index=True)
bid = int(st.selectbox("Generate a findings summary for batch", batches["id"].tolist()))


def build(bid):
    tx = db.query("SELECT sender, amount, flagged, reasons FROM transactions WHERE batch_id=?", (bid,))
    al = db.query("SELECT status FROM alert WHERE batch_id=?", (bid,))
    cs = db.query("""SELECT COUNT(DISTINCT c.id) AS n FROM cases c JOIN case_alert ca ON ca.case_id=c.id
                     JOIN alert a ON a.id=ca.alert_id WHERE a.batch_id=?""", (bid,)).iloc[0]["n"]
    fl = tx[tx["flagged"] == 1]
    hits = fl["reasons"].fillna("").str.split("; ").explode().str.split(":").str[0].str.strip()
    hits = hits[hits != ""].value_counts()
    mules = fl["reasons"].str.extract(r"Mule pass-through: account (\S+)")[0].dropna().nunique()
    top = fl.groupby("sender")["amount"].agg(["size", "sum"]).sort_values("size", ascending=False).head(5)
    return "\n".join([f"# Findings summary: batch {bid}", f"Generated by {user['username']} on {db.now()}", "",
                      f"- Transactions analysed: {len(tx):,}",
                      f"- Flagged: {len(fl):,} ({len(fl) / max(len(tx), 1):.2%}), value {fl['amount'].sum():,.0f}",
                      f"- Suspected mule accounts: {mules}", f"- Cases opened from this batch: {int(cs)}",
                      "- Alert status: " + (", ".join(f"{k} {v}" for k, v in al['status'].value_counts().items()) or "none"),
                      "", "## Flags by rule"] + [f"- {k}: {v}" for k, v in hits.items()] +
                     ["", "## Top flagged senders"] +
                     [f"- {s}: {int(r['size'])} alerts, value {r['sum']:,.0f}" for s, r in top.iterrows()])


if st.button("Generate & save report", type="primary"):
    db.execute("INSERT INTO report(title,batch_id,generated_by,generated_at,content) VALUES(?,?,?,?,?)",
               (f"Findings summary batch {bid}", bid, user["username"], db.now(), build(bid)))
    db.log(user["username"], "report_generated", f"batch {bid}")
    st.success("Report saved.")

flagged = db.query("""SELECT t.id AS tx_id, t.sender, t.receiver, t.amount, t.tx_date, a.risk_score, a.reasons,
                             a.status, a.reviewed_by, a.note
                      FROM alert a JOIN transactions t ON t.id=a.tx_id WHERE a.batch_id=?
                      ORDER BY a.risk_score DESC""", (bid,))
st.download_button("⬇️ Download flagged transactions (CSV)", flagged.to_csv(index=False).encode(),
                   f"flagged_batch_{bid}.csv", "text/csv")

st.subheader("Saved reports")
for r in db.query("SELECT * FROM report ORDER BY id DESC LIMIT 20").itertuples():
    with st.expander(f"{r.title} · {r.generated_at} · {r.generated_by}"):
        st.markdown(r.content)
        st.download_button("Download (.md)", r.content.encode(), f"report_{r.id}.md", key=f"dl{r.id}")
